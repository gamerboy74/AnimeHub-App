/**
 * Returns a completely random anime avatar from the curated list.
 */
export function getRandomAnimeAvatar(): AnimeAvatar {
  const index = Math.floor(Math.random() * ANIME_AVATARS.length);
  return ANIME_AVATARS[index];
}

/**
 * Returns a deterministic anime avatar based on a unique identifier (e.g., user ID or username).
 * Ensures the same user gets the same avatar consistently unless changed.
 */
export function getAnimeAvatarForUser(userIdOrName: string): AnimeAvatar {
  if (!userIdOrName) return ANIME_AVATARS[0];
  let hash = 0;
  for (let i = 0; i < userIdOrName.length; i++) {
    hash = (hash << 5) - hash + userIdOrName.charCodeAt(i);
    hash |= 0; // Convert to 32bit integer
  }
  const index = Math.abs(hash) % ANIME_AVATARS.length;
  return ANIME_AVATARS[index];
}

/**
 * Find an avatar by its URL or ID.
 */
export function findAnimeAvatar(idOrUrl?: string | null): AnimeAvatar | undefined {
  if (!idOrUrl) return undefined;
  return ANIME_AVATARS.find(a => a.id === idOrUrl || a.url === idOrUrl);
}
